try

    cd(packageParent);
    zip(zipFile, packageName);
    cd(originalFolder);

catch zipError

    cd(originalFolder);

    warning('Could not create ZIP file: %s', ...
        zipError.message);
end

fprintf('\n');
fprintf('============================================================\n');
fprintf('FIGURE S.2 SAMPLE-SIZE VALIDATION COMPLETED\n');
fprintf('============================================================\n');
fprintf('Package folder:\n%s\n\n', packageFolder);

for scenarioIndex = 1:numel(scenarios)

    fprintf('Scenario %d figure:\n%s\n\n', ...
        scenarios(scenarioIndex).id, ...
        fullfile( ...
            figuresFolder, ...
            [scenarios(scenarioIndex).fileName, '.png']));
end

fprintf('MATLAB code:\n%s\n\n', packageCode);

if exist(zipFile, 'file')
    fprintf('ZIP file:\n%s\n\n', zipFile);
end

fprintf('============================================================\n');

end


function summary = simulate_observed_summary( ...
    numberOfClusters, Rp, Rs, ks, pObs, Ip, Is)

primaryCounts = ...
    geornd(1 / Rp, numberOfClusters, 1) + 1;

secondaryCounts = simulate_secondary_totals( ...
    numberOfClusters, primaryCounts, Rs, ks);

primaryPositive = binornd(primaryCounts, Ip);
primaryNegative = primaryCounts - primaryPositive;

secondaryPositive = binornd(secondaryCounts, Is);
secondaryNegative = secondaryCounts - secondaryPositive;

observedPrimaryPositive = ...
    binornd(primaryPositive, pObs);

observedPrimaryNegative = ...
    binornd(primaryNegative, pObs);

observedSecondaryPositive = ...
    binornd(secondaryPositive, pObs);

observedSecondaryNegative = ...
    binornd(secondaryNegative, pObs);

observedPrimaryTotal = ...
    observedPrimaryPositive + observedPrimaryNegative;

observedSecondaryTotal = ...
    observedSecondaryPositive + observedSecondaryNegative;

observedTotalByCluster = ...
    observedPrimaryTotal + observedSecondaryTotal;

nonemptyClusters = observedTotalByCluster > 0;
totalObserved = sum(observedTotalByCluster);

if totalObserved == 0

    summary.totalObserved = 0;
    summary.naiveRs = NaN;
    summary.naiveOR = NaN;
    summary.primaryPositive = NaN;
    summary.primaryNegative = NaN;
    summary.secondaryPositive = NaN;
    summary.secondaryNegative = NaN;

    return;
end

classifiedPrimaryPositive = ...
    zeros(numberOfClusters, 1);

classifiedPrimaryNegative = ...
    zeros(numberOfClusters, 1);

hasObservedPrimary = observedPrimaryTotal > 0;
probabilityPositive = zeros(numberOfClusters, 1);

probabilityPositive(hasObservedPrimary) = ...
    observedPrimaryPositive(hasObservedPrimary) ./ ...
    observedPrimaryTotal(hasObservedPrimary);

classifiedPrimaryPositive(hasObservedPrimary) = ...
    rand(sum(hasObservedPrimary), 1) < ...
    probabilityPositive(hasObservedPrimary);

classifiedPrimaryNegative(hasObservedPrimary) = ...
    1 - classifiedPrimaryPositive(hasObservedPrimary);

hasOnlyObservedSecondary = ...
    (~hasObservedPrimary) & ...
    (observedSecondaryTotal > 0);

probabilityPositive(:) = 0;

probabilityPositive(hasOnlyObservedSecondary) = ...
    observedSecondaryPositive(hasOnlyObservedSecondary) ./ ...
    observedSecondaryTotal(hasOnlyObservedSecondary);

classifiedPrimaryPositive(hasOnlyObservedSecondary) = ...
    rand(sum(hasOnlyObservedSecondary), 1) < ...
    probabilityPositive(hasOnlyObservedSecondary);

classifiedPrimaryNegative(hasOnlyObservedSecondary) = ...
    1 - classifiedPrimaryPositive(hasOnlyObservedSecondary);

QpPositive = ...
    sum(classifiedPrimaryPositive(nonemptyClusters));

QpNegative = ...
    sum(classifiedPrimaryNegative(nonemptyClusters));

totalPositive = sum( ...
    observedPrimaryPositive + observedSecondaryPositive);

totalNegative = sum( ...
    observedPrimaryNegative + observedSecondaryNegative);

QsPositive = totalPositive - QpPositive;
QsNegative = totalNegative - QpNegative;

naiveRs = ...
    (QsPositive + QsNegative) / totalObserved;

a = QpPositive;
b = QpNegative;
c = QsPositive;
d = QsNegative;

naiveOR = ...
    ((a + 0.5) * (d + 0.5)) / ...
    ((b + 0.5) * (c + 0.5));

summary.totalObserved = totalObserved;
summary.naiveRs = naiveRs;
summary.naiveOR = naiveOR;
summary.primaryPositive = QpPositive;
summary.primaryNegative = QpNegative;
summary.secondaryPositive = QsPositive;
summary.secondaryNegative = QsNegative;

end


function totalSecondary = simulate_secondary_totals( ...
    numberOfClusters, primaryCounts, Rs, ks)

totalSecondary = zeros(numberOfClusters, 1);
activeGeneration = primaryCounts;

maximumGeneration = 10000;
generation = 0;

while any(activeGeneration > 0)

    generation = generation + 1;

    if generation > maximumGeneration
        warning('Maximum generation limit reached.');
        break;
    end

    activeIndex = activeGeneration > 0;

    shape = activeGeneration(activeIndex) * ks;
    scale = Rs / ks;

    lambda = gamrnd(shape, scale);
    newCases = poissrnd(lambda);

    activeGeneration(:) = 0;
    activeGeneration(activeIndex) = newCases;

    totalSecondary = totalSecondary + activeGeneration;
end

end


function lookup = precompute_analytical_lookup( ...
    iMax, Rp, ks, pObs, rsGrid, precomputation)

[Cpp, Cps] = primary_classifier_probabilities( ...
    iMax, Rp, pObs);

CspGrid = NaN(size(rsGrid));
CssGrid = NaN(size(rsGrid));
observedRsGrid = NaN(size(rsGrid));

for gridIndex = 1:numel(rsGrid)

    rs = rsGrid(gridIndex);

    [Csp, Css] = secondary_classifier_probabilities( ...
        precomputation, Rp, rs, ks, pObs);

    CspGrid(gridIndex) = Csp;
    CssGrid(gridIndex) = Css;

    observedRsGrid(gridIndex) = ...
        ((1 - rs) * Cps + rs * Css) / pObs;
end

if any(~isfinite(observedRsGrid))
    error('The analytical lookup contains nonfinite values.');
end

[observedRsSorted, sortIndex] = sort(observedRsGrid);
rsSorted = rsGrid(sortIndex);

[observedRsUnique, uniqueIndex] = ...
    unique(observedRsSorted);

rsUnique = rsSorted(uniqueIndex);

lookup.Cpp = Cpp;
lookup.Cps = Cps;
lookup.rsGrid = rsGrid;
lookup.CspGrid = CspGrid;
lookup.CssGrid = CssGrid;
lookup.observedRsUnique = observedRsUnique;
lookup.rsUnique = rsUnique;

end


function correctedRs = infer_corrected_Rs( ...
    observedRs, lookup)

minimumObservedRs = min(lookup.observedRsUnique);
maximumObservedRs = max(lookup.observedRsUnique);

boundedObservedRs = min( ...
    max(observedRs, minimumObservedRs), ...
    maximumObservedRs);

correctedRs = interp1( ...
    lookup.observedRsUnique, ...
    lookup.rsUnique, ...
    boundedObservedRs, ...
    'linear');

end


function precomputation = ...
    make_secondary_precomputation(iMax, ks)

[I, N] = ndgrid(1:iMax, 1:iMax);

validMask = N > I;
base = NaN(iMax, iMax);

base(validMask) = ...
    log(I(validMask)) ...
    - log(N(validMask)) ...
    + gammaln( ...
        ks * N(validMask) + ...
        N(validMask) - ...
        I(validMask)) ...
    - gammaln( ...
        N(validMask) - ...
        I(validMask) + 1) ...
    - gammaln(ks * N(validMask));

precomputation.iMax = iMax;
precomputation.mask = validMask;
precomputation.base = base;
precomputation.nMinusI = N - I;
precomputation.coefficient = ks * N + N - I;

end


function [Csp, Css] = ...
    secondary_classifier_probabilities( ...
    precomputation, Rp, Rs, ks, pObs)

iMax = precomputation.iMax;
iValues = 1:iMax;

clusterSizeProbability = zeros(iMax, iMax);

logProbability = ...
    precomputation.base ...
    + precomputation.nMinusI .* log(Rs / ks) ...
    - precomputation.coefficient .* ...
    log(1 + Rs / ks);

clusterSizeProbability(precomputation.mask) = ...
    exp(logProbability(precomputation.mask));

primaryCountProbability = ...
    (1 - 1 / Rp).^(iValues - 1) / Rp;

weightedProbability = ...
    clusterSizeProbability .* ...
    primaryCountProbability(:);

rightCumulativeSum = ...
    fliplr(cumsum(fliplr(weightedProbability), 2));

topRightSum = cumsum(rightCumulativeSum, 1);

secondaryPositionProbability = zeros(1, iMax);

linearIndex = sub2ind( ...
    [iMax, iMax], ...
    1:(iMax - 1), ...
    2:iMax);

secondaryPositionProbability(2:iMax) = ...
    topRightSum(linearIndex);

secondaryPositionProbability = ...
    secondaryPositionProbability * ...
    (1 - Rs) / Rp / Rs;

if pObs == 1

    Csp = 0;

else

    Csp = sum( ...
        secondaryPositionProbability .* ...
        pObs .* ...
        exp(log(1 - pObs) .* (iValues - 1)));
end

Css = pObs - Csp;

end


function [Cpp, Cps] = ...
    primary_classifier_probabilities( ...
    iMax, Rp, pObs)

iValues = 1:iMax;

primaryCountProbability = ...
    (1 - 1 / Rp).^(iValues - 1) / Rp;

temporarySum = ...
    (1 / Rp) * ...
    cumsum(primaryCountProbability(end:-1:1));

primaryPositionProbability = ...
    temporarySum(end:-1:1);

if pObs == 1

    Cpp = primaryPositionProbability(1);

else

    Cpp = sum( ...
        primaryPositionProbability .* ...
        pObs .* ...
        exp(log(1 - pObs) .* (iValues - 1)));
end

Cps = pObs - Cpp;

end


function trueProbabilities = recover_true_probabilities( ...
    pObs, Cpp, Cps, Csp, Css, ...
    Xpn, Xpp, Xsn, Xsp)

Qpn = ...
    pObs * (Xsn * Csp - Xpn * Css) / ...
    (Cps * Csp - Cpp * Css);

Qpp = ...
    pObs * (Xsp * Csp - Xpp * Css) / ...
    (Cps * Csp - Cpp * Css);

Qsn = ...
    pObs * (Xsn - Xpn * Cps / Cpp) / ...
    (Css - Csp * Cps / Cpp);

Qsp = ...
    pObs * (Xsp - Xpp * Cps / Cpp) / ...
    (Css - Csp * Cps / Cpp);

trueProbabilities = [Qpn, Qpp, Qsn, Qsp];

end


function output = row_percentile( ...
    inputMatrix, percentileValue)

numberOfRows = size(inputMatrix, 1);
output = NaN(numberOfRows, 1);

for rowIndex = 1:numberOfRows

    values = inputMatrix(rowIndex, :);
    values = values(isfinite(values));

    if ~isempty(values)
        output(rowIndex) = ...
            prctile(values, percentileValue);
    end
end

end


