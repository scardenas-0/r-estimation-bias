%{
Accepted-paper simulation settings:
True R_s = 0.50
k_s = 0.30
True OR = 2.00
Simulations per sample size = 100
Numbers of clusters = [100 200 300 400 500 600 700 800 900 1000]

The figures folder contains the six-panel Figure S.2 and the three separate two-panel scenario figures.


%}

function generate_figure_S2_sample_size_validation()

clc;
close all;

sourceBase = mfilename('fullpath');

if isempty(sourceBase)
    error('Save this MATLAB file before running it.');
end

sourceFile = [sourceBase, '.m'];
sourceFolder = fileparts(sourceFile);

packageName = 'Figure_S2_Sample_Size_Validation';
[~, currentFolderName] = fileparts(sourceFolder);

if strcmpi(currentFolderName, packageName)
    packageFolder = sourceFolder;
else
    packageFolder = fullfile(sourceFolder, packageName);
end

figuresFolder = fullfile(packageFolder, 'figures');
resultsFolder = fullfile(packageFolder, 'data');

create_folder(packageFolder);
create_folder(figuresFolder);
create_folder(resultsFolder);

clear_folder_files(figuresFolder);
clear_folder_files(resultsFolder);

packageCode = fullfile( ...
    packageFolder, ...
    'generate_figure_S2_sample_size_validation.m');

if ~strcmpi(sourceFile, packageCode)

    if exist(packageCode, 'file')
        delete(packageCode);
    end

    [copySuccess, copyMessage] = copyfile(sourceFile, packageCode);

    if ~copySuccess
        error('Could not copy the MATLAB file: %s', copyMessage);
    end
end

rng(1, 'twister');

Rs = 0.5;
ks = 0.3;

Ip = 2/3;
Is = 0.5;

trueOR = ...
    (Ip * (1 - Is)) / ...
    ((1 - Ip) * Is);

numRuns = 200;
clusterNumbers = 100:100:1000;

iMax = 500;
rsGrid = linspace(0.001, 0.95, 900);

secondaryPrecomputation = ...
    make_secondary_precomputation(iMax, ks);

scenarios = struct( ...
    'id', {2, 3, 4}, ...
    'name', { ...
        'Imperfect observation only', ...
        'Overlapping transmission chains only', ...
        'Imperfect observation and overlapping transmission chains'}, ...
    'fileName', { ...
        'Scenario_2_Imperfect_Observation_Only', ...
        'Scenario_3_Overlapping_Transmission_Chains_Only', ...
        'Scenario_4_Imperfect_Observation_and_Overlap'}, ...
    'Rp', {1.0, 1.5, 1.5}, ...
    'pObs', {0.5, 1.0, 0.5}, ...
    'RsLimits', { ...
        [0.25, 0.70], ...
        [0.30, 0.70], ...
        [0.30, 0.65]}, ...
    'ORLimits', { ...
        [0, 5], ...
        [0, 5], ...
        [0, 5]});

fprintf('\n');
fprintf('============================================================\n');
fprintf('FIGURE S.2 SAMPLE-SIZE VALIDATION STARTED\n');
fprintf('============================================================\n');
fprintf('Output folder:\n%s\n\n', packageFolder);
fprintf('True R_s                     = %.2f\n', Rs);
fprintf('Dispersion parameter, k_s   = %.2f\n', ks);
fprintf('Trait probability, I_p      = %.4f\n', Ip);
fprintf('Trait probability, I_s      = %.4f\n', Is);
fprintf('True odds ratio             = %.2f\n', trueOR);
fprintf('Simulations per sample size = %d\n', numRuns);
fprintf('Numbers of clusters         = %s\n', ...
    mat2str(clusterNumbers));
fprintf('============================================================\n\n');

allResults = cell(numel(scenarios), 1);
summaryTables = cell(numel(scenarios), 1);

for scenarioIndex = 1:numel(scenarios)

    scenario = scenarios(scenarioIndex);

    fprintf('------------------------------------------------------------\n');
    fprintf('Scenario %d: %s\n', ...
        scenario.id, scenario.name);
    fprintf('R_p = %.2f, p_obs = %.2f\n', ...
        scenario.Rp, scenario.pObs);
    fprintf('Preparing analytical lookup...\n');

    lookup = precompute_analytical_lookup( ...
        iMax, ...
        scenario.Rp, ...
        ks, ...
        scenario.pObs, ...
        rsGrid, ...
        secondaryPrecomputation);

    numberOfSampleSizes = numel(clusterNumbers);

    naiveRsRuns = NaN(numberOfSampleSizes, numRuns);
    correctedRsRuns = NaN(numberOfSampleSizes, numRuns);
    naiveORRuns = NaN(numberOfSampleSizes, numRuns);
    correctedORRuns = NaN(numberOfSampleSizes, numRuns);

    for sampleIndex = 1:numberOfSampleSizes

        numberOfClusters = clusterNumbers(sampleIndex);

        fprintf('  Simulating %4d clusters: ', ...
            numberOfClusters);

        for runIndex = 1:numRuns

            summary = simulate_observed_summary( ...
                numberOfClusters, ...
                scenario.Rp, ...
                Rs, ...
                ks, ...
                scenario.pObs, ...
                Ip, ...
                Is);

            if summary.totalObserved < 5
                continue;
            end

            naiveRs = summary.naiveRs;

            correctedRs = infer_corrected_Rs( ...
                naiveRs, lookup);

            Cpp = lookup.Cpp;
            Cps = lookup.Cps;

            Csp = interp1( ...
                lookup.rsGrid, ...
                lookup.CspGrid, ...
                correctedRs, ...
                'linear', ...
                'extrap');

            Css = interp1( ...
                lookup.rsGrid, ...
                lookup.CssGrid, ...
                correctedRs, ...
                'linear', ...
                'extrap');

            Xpp = ...
                summary.primaryPositive / ...
                summary.totalObserved;

            Xpn = ...
                summary.primaryNegative / ...
                summary.totalObserved;

            Xsp = ...
                summary.secondaryPositive / ...
                summary.totalObserved;

            Xsn = ...
                summary.secondaryNegative / ...
                summary.totalObserved;

            trueProbabilities = recover_true_probabilities( ...
                scenario.pObs, ...
                Cpp, ...
                Cps, ...
                Csp, ...
                Css, ...
                Xpn, ...
                Xpp, ...
                Xsn, ...
                Xsp);

            correctedOR = NaN;

            if all(isfinite(trueProbabilities)) && ...
                    all(trueProbabilities > 0)

                candidateOR = ...
                    (trueProbabilities(2) * ...
                    trueProbabilities(3)) / ...
                    (trueProbabilities(1) * ...
                    trueProbabilities(4));

                if isfinite(candidateOR) && ...
                        isreal(candidateOR) && ...
                        candidateOR > 0

                    correctedOR = candidateOR;
                end
            end

            naiveRsRuns(sampleIndex, runIndex) = ...
                naiveRs;

            correctedRsRuns(sampleIndex, runIndex) = ...
                correctedRs;

            naiveORRuns(sampleIndex, runIndex) = ...
                summary.naiveOR;

            correctedORRuns(sampleIndex, runIndex) = ...
                correctedOR;
        end

        validRs = sum(isfinite( ...
            correctedRsRuns(sampleIndex, :)));

        validOR = sum(isfinite( ...
            correctedORRuns(sampleIndex, :)));

        fprintf(['completed. Valid runs: ', ...
            'R_s = %d/%d, OR = %d/%d\n'], ...
            validRs, numRuns, validOR, numRuns);
    end

    result = struct();

    result.scenarioID = scenario.id;
    result.scenarioName = scenario.name;
    result.Rp = scenario.Rp;
    result.pObs = scenario.pObs;

    result.medianNaiveRs = ...
        row_percentile(naiveRsRuns, 50);

    result.medianCorrectedRs = ...
        row_percentile(correctedRsRuns, 50);

    result.correctedRsLower95 = ...
        row_percentile(correctedRsRuns, 2.5);

    result.correctedRsUpper95 = ...
        row_percentile(correctedRsRuns, 97.5);

    result.medianNaiveOR = ...
        row_percentile(naiveORRuns, 50);

    result.medianCorrectedOR = ...
        row_percentile(correctedORRuns, 50);

    result.correctedORLower95 = ...
        row_percentile(correctedORRuns, 2.5);

    result.correctedORUpper95 = ...
        row_percentile(correctedORRuns, 97.5);

    result.validCorrectedRsRuns = ...
        sum(isfinite(correctedRsRuns), 2);

    result.validCorrectedORRuns = ...
        sum(isfinite(correctedORRuns), 2);

    result.naiveRsRuns = naiveRsRuns;
    result.correctedRsRuns = correctedRsRuns;
    result.naiveORRuns = naiveORRuns;
    result.correctedORRuns = correctedORRuns;

    allResults{scenarioIndex} = result;

    summaryTable = table( ...
        repmat(scenario.id, numberOfSampleSizes, 1), ...
        repmat({scenario.name}, numberOfSampleSizes, 1), ...
        repmat(scenario.Rp, numberOfSampleSizes, 1), ...
        repmat(scenario.pObs, numberOfSampleSizes, 1), ...
        repmat(numRuns, numberOfSampleSizes, 1), ...
        clusterNumbers(:), ...
        result.medianNaiveRs, ...
        result.medianCorrectedRs, ...
        result.correctedRsLower95, ...
        result.correctedRsUpper95, ...
        result.medianNaiveOR, ...
        result.medianCorrectedOR, ...
        result.correctedORLower95, ...
        result.correctedORUpper95, ...
        result.validCorrectedRsRuns, ...
        result.validCorrectedORRuns, ...
        'VariableNames', { ...
        'ScenarioID', ...
        'ScenarioName', ...
        'Rp', ...
        'p_obs', ...
        'SimulationRuns', ...
        'NumberOfClusters', ...
        'MedianNaiveRs', ...
        'MedianCorrectedRs', ...
        'CorrectedRsLower95', ...
        'CorrectedRsUpper95', ...
        'MedianNaiveOR', ...
        'MedianCorrectedOR', ...
        'CorrectedORLower95', ...
        'CorrectedORUpper95', ...
        'ValidCorrectedRsRuns', ...
        'ValidCorrectedORRuns'});

    summaryTables{scenarioIndex} = summaryTable;

    writetable( ...
        summaryTable, ...
        fullfile( ...
            resultsFolder, ...
            [scenario.fileName, '_Summary.csv']));

    scenarioResult = result;

    save( ...
        fullfile( ...
            resultsFolder, ...
            [scenario.fileName, '_Results.mat']), ...
        'scenarioResult', ...
        'clusterNumbers', ...
        'Rs', ...
        'ks', ...
        'Ip', ...
        'Is', ...
        'trueOR', ...
        'numRuns');

    figureHandle = make_scenario_figure( ...
        clusterNumbers, ...
        result, ...
        Rs, ...
        trueOR, ...
        scenario);

    figureBase = fullfile( ...
        figuresFolder, ...
        scenario.fileName);

    save_figure( ...
        figureHandle, ...
        [figureBase, '.png'], ...
        [figureBase, '.jpg'], ...
        [figureBase, '.pdf']);

    close(figureHandle);

    fprintf('Scenario %d saved successfully.\n\n', ...
        scenario.id);
end

allScenariosTable = vertcat(summaryTables{:});

writetable( ...
    allScenariosTable, ...
    fullfile( ...
        resultsFolder, ...
        'All_Scenarios_Summary.csv'));

matlabVersion = version;
generationTime = datestr(now, 30);

save( ...
    fullfile( ...
        resultsFolder, ...
        'All_Scenarios_Complete_Results.mat'), ...
    'allResults', ...
    'scenarios', ...
    'clusterNumbers', ...
    'Rs', ...
    'ks', ...
    'Ip', ...
    'Is', ...
    'trueOR', ...
    'numRuns', ...
    'matlabVersion', ...
    'generationTime');

readmeFile = fullfile(packageFolder, 'README.md');

write_readme( ...
    readmeFile, ...
    numRuns, ...
    clusterNumbers, ...
    Rs, ...
    ks, ...
    Ip, ...
    Is, ...
    trueOR);

packageParent = fileparts(packageFolder);

