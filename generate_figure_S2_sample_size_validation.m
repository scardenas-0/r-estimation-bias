end


function create_folder(folderPath)

if ~exist(folderPath, 'dir')

    [success, message] = mkdir(folderPath);

    if ~success
        error('Could not create folder: %s', message);
    end
end

end


function clear_folder_files(folderPath)

items = dir(folderPath);

for itemIndex = 1:numel(items)

    if ~items(itemIndex).isdir

        delete(fullfile( ...
            folderPath, ...
            items(itemIndex).name));
    end
end

end


